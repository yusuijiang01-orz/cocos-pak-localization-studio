def is_code_line(text):
    """Check if text is code that should be preserved."""
    text_stripped = text.strip()
    if text_stripped.startswith('function '):
        return True
    if text_stripped.startswith('return '):
        return True
    if text_stripped.startswith('-- '):
        return True
    if '.spr' in text_stripped or '.lua' in text_stripped or '.wav' in text_stripped or '.mp3' in text_stripped:
        if '\\' in text_stripped or '/' in text_stripped:
            return True
    if re.match(r'^[a-zA-Z_][a-zA-Z0-9_]*\s*\(', text_stripped):
        return True
    return False

def preserve_tags(text):
    """Extract and preserve tags, return (clean_text, tag_map)"""
    tag_map = {}
    counter = [0]
    
    def make_placeholder():
        counter[0] += 1
        return f"\x00TAG{counter[0]}\x00"
    
    def replace_tag(m):
        ph = make_placeholder()
        tag_map[ph] = m.group(0)
        return ph
    
    # Preserve <c=color>...</c> patterns (closing is <c>)
    text = re.sub(r'<c=[^>]*>.*?<c>', replace_tag, text, flags=re.DOTALL)
    # Preserve <color=name>...</color> patterns
    text = re.sub(r'<color=[^>]*>.*?<color>', replace_tag, text, flags=re.DOTALL)
    # Preserve <enter>
    text = re.sub(r'<enter>', replace_tag, text)
    # Position tags are runtime structures. Translating any content inside
    # them can make the whole task line disappear in game.
    text = re.sub(r'<(?:npc)?pos=[^>]*>', replace_tag, text, flags=re.I)
    # Preserve other angle-bracket tags
    text = re.sub(r'<[^>]+>', replace_tag, text)
    
    return text, tag_map

def restore_tags(text, tag_map):
    """Restore preserved tags."""
    for ph, tag in tag_map.items():
        text = text.replace(ph, tag)
    return text

def translate_text_segment(text):
    """Translate a plain text segment (no tags) using dictionary."""
    if not text or not text.strip():
        return text
    
    result = text
    
    # Try phrase matching first (longest first)
    sorted_phrases = sorted(PHRASES.keys(), key=len, reverse=True)
    for phrase in sorted_phrases:
        if phrase in result:
            result = result.replace(phrase, PHRASES[phrase])
    
    # Then word matching
    tokens = re.findall(r'[A-Za-zÀ-ỹ]+|[^A-Za-zÀ-ỹ]+', result)
    translated_tokens = []
    for token in tokens:
        if re.match(r'^[A-Za-zÀ-ỹ]+$', token):
            if token in WORDS:
                translated_tokens.append(WORDS[token])
            elif token.lower() in WORDS:
                translated_tokens.append(WORDS[token.lower()])
            else:
                translated_tokens.append(token)
        else:
            translated_tokens.append(token)
    
    result = ''.join(translated_tokens)
    return result

def translate_inner_tag_content(tag_content):
    """Translate the content inside a tag like <c=yellow>Thanh Linh Ngọc Bội<c>"""
    m = re.match(r'(<c=[^>]*>)(.*?)(<c>)', tag_content, flags=re.DOTALL)
    if m:
        opening, content, closing = m.groups()
        translated = translate_text_segment(content)
        return f"{opening}{translated}{closing}"
    
    m = re.match(r'(<color=[^>]*>)(.*?)(<color>)', tag_content, flags=re.DOTALL)
    if m:
        opening, content, closing = m.groups()
        translated = translate_text_segment(content)
        return f"{opening}{translated}{closing}"
    
    return tag_content

def clean_chinese_spaces(text):
    """Remove spaces between Chinese characters, preserve other spacing."""
    # Remove space between two Chinese characters
    result = re.sub(r'([\u4e00-\u9fff])\s+([\u4e00-\u9fff])', r'\1\2', text)
    # Repeat to handle consecutive spaces
    for _ in range(3):
        result = re.sub(r'([\u4e00-\u9fff])\s+([\u4e00-\u9fff])', r'\1\2', result)
    # Remove space between Chinese char and common Chinese punctuation
    cn_punct = '，。！？、；：（）《》【】'
    result = re.sub(r'([\u4e00-\u9fff])\s+([' + cn_punct + r'])', r'\1\2', result)
    result = re.sub(r'([' + cn_punct + r'])\s+([\u4e00-\u9fff])', r'\1\2', result)
    return result

def translate_string(text):
    """Full translation pipeline for a single string."""
    if not text:
        return text
    
    # Skip code lines
    if is_code_line(text):
        return text
    
    # Extract and preserve tags
    clean_text, tag_map = preserve_tags(text)
    
    # Translate the clean text
    translated = translate_text_segment(clean_text)
    
    # Restore tags (translate inner content of color tags)
    for ph, tag in list(tag_map.items()):
        if re.match(r'<c=[^>]*>.*<c>', tag) or re.match(r'<color=[^>]*>.*<color>', tag):
            tag_map[ph] = translate_inner_tag_content(tag)
    
    result = restore_tags(translated, tag_map)
    
    # Clean up spaces between Chinese characters
    result = clean_chinese_spaces(result)
    
    return result

def main():
    input_file = 'updatefs_localization.csv'
    output_file = 'updatefs_localization_zh.csv'
    
    print(f"Reading {input_file}...")
    rows = []
    with open(input_file, 'r', encoding='utf-8-sig') as f:
        reader = csv.reader(f)
        header = next(reader)
        for row in reader:
            rows.append(row)
    
    print(f"Total rows: {len(rows)}")
    
    # Build unique value cache
    unique_vals = {}
    for row in rows:
        if len(row) > 1:
            val = row[1]
            if val not in unique_vals:
                unique_vals[val] = None
    
    print(f"Unique values to translate: {len(unique_vals)}")
    
    # Translate unique values
    translated_count = 0
    for val in unique_vals:
        unique_vals[val] = translate_string(val)
        translated_count += 1
        if translated_count % 5000 == 0:
            print(f"  Translated {translated_count}/{len(unique_vals)} unique values...")
    
    print(f"Translation complete. Writing output...")
    
    # Write output
    with open(output_file, 'w', encoding='utf-8-sig', newline='') as f:
        writer = csv.writer(f)
        writer.writerow(header)
        for row in rows:
            if len(row) > 1:
                row[1] = unique_vals.get(row[1], row[1])
            writer.writerow(row)
    
    print(f"Output written to {output_file}")
    
    # Print samples
    print("\n--- Translation samples (changed only) ---")
    sample_count = 0
    for val, trans in list(unique_vals.items())[:200]:
        if val != trans and not is_code_line(val):
            print(f"  ORIG:  {repr(val[:100])}")
            print(f"  TRANS: {repr(trans[:100])}")
            print()
            sample_count += 1
            if sample_count >= 20:
                break

if __name__ == '__main__':
    main()
